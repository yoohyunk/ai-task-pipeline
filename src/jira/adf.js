/**
 * Atlassian Document Format helpers. Jira REST API v3 requires ADF for the
 * description field, not plain text.
 */
function toADF(text) {
  return {
    type: 'doc',
    version: 1,
    content: [
      {
        type: 'paragraph',
        content: [{ type: 'text', text: text || '' }],
      },
    ],
  };
}

const heading = (text, level = 3) => ({
  type: 'heading',
  attrs: { level },
  content: [{ type: 'text', text }],
});

const para = (text) => ({
  type: 'paragraph',
  content: [{ type: 'text', text: text || '' }],
});

const bulletList = (items) => ({
  type: 'bulletList',
  content: (items || []).filter(Boolean).map((t) => ({
    type: 'listItem',
    content: [para(t)],
  })),
});

/**
 * Render a PRD object as rich ADF (headings + bullet lists) for a Jira ticket.
 * @param {object} prd - { background, problem, requirements[], acceptanceCriteria[], outOfScope }
 * @param {object} task - the source task (for the metadata line)
 */
function prdToADF(prd, task = {}) {
  const meta =
    `Source: ${task.source || 'n/a'}` +
    (task.sourceChannel ? ` ${task.sourceChannel}` : '') +
    ` · Priority: ${task.priority || 'medium'}` +
    (task.assignee_hint ? ` · Suggested: ${task.assignee_hint}` : '');

  const content = [para(meta)];

  content.push(heading('Background'), para(prd.background));
  content.push(heading('Problem'), para(prd.problem));
  content.push(heading('Requirements'), bulletList(prd.requirements));
  content.push(heading('Acceptance criteria'), bulletList(prd.acceptanceCriteria));
  if (prd.outOfScope) content.push(heading('Out of scope'), para(prd.outOfScope));
  content.push(para('— Generated by the AI task pipeline'));

  return { type: 'doc', version: 1, content };
}

module.exports = { toADF, prdToADF };
